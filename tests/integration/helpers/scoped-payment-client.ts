import type {Sql} from 'postgres';

/** Keep global maintenance tests inside their fixture, without changing demo orders. */
export function scopedPaymentClient(client:Sql, companyId:string):Sql {
 return new Proxy(client, {
  apply(target, thisArg, args) {
   const [strings,...values]=args as [TemplateStringsArray,...unknown[]];
   const parts=[...strings];
   const queued=parts[0]?.startsWith("select id from public.payment_events where status='RECEIVED'");
   const pending=parts[0]?.startsWith('select p.id as "paymentId",p.provider_order_id as "orderId"');
   const expiring=parts[0]?.startsWith('select id,held_by_user_id as "ownerId" from public.seat_holds');
   if(queued||pending||expiring) {
    const index=parts.findIndex(part=>part.includes(' order by '));
    if(index<0)throw new Error('Maintenance query changed; update fixture scope.');
    // UUID is generated by the fixture, not supplied by external input.
    if(!/^[0-9a-f-]{36}$/.test(companyId))throw new Error('Invalid fixture company.');
    const condition=queued?` and payment_id in (select id from public.payments where company_id='${companyId}'::uuid)`:` and ${expiring?'company_id':'p.company_id'}='${companyId}'::uuid`;
    parts[index]=parts[index].replace(' order by ',condition+' order by ');
    const scoped=Object.assign(parts,{raw:parts});
    return Reflect.apply(target,thisArg,[scoped,...values]);
   }
   return Reflect.apply(target,thisArg,args);
  },
 });
}
